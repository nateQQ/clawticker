#!/usr/bin/env python3
"""Generate firmware/src/sprites.c + sprites.h from assets/mascot/claudepix-frames.json.
Each preset becomes a palette (RGB565 + alpha) and 20x20 frames of palette indices.
Usage: python3 tools/gen_sprites.py"""
import json, os

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
data = json.load(open(os.path.join(root, "assets", "mascot", "claudepix-frames.json")))
N = data["grid"]

def rgb(hexstr):
    h = hexstr.lstrip("#")
    if len(h) == 3:
        h = "".join(ch * 2 for ch in h)
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)

c = ['#include "sprites.h"', "", "// Generated by tools/gen_sprites.py from assets/mascot/claudepix-frames.json, do not edit.", ""]
entries = []
for p in data["presets"]:
    slug = p["slug"]
    pal = []
    for col in p["palette"]:
        if col == "transparent":
            pal.append("0,0,0,0")
        else:
            r, g, b = rgb(col)
            pal.append(f"{r},{g},{b},255")
    frames = p["frames"]
    pix = []
    for f in frames:
        for row in f["grid"]:
            pix.extend(row)
    holds = [f["hold_ms"] for f in frames]
    c.append(f"static const uint8_t {slug}_pal[] = {{{', '.join(pal)}}};")
    c.append(f"static const uint16_t {slug}_hold[] = {{{', '.join(map(str, holds))}}};")
    rows = ",\n".join("    " + ", ".join(map(str, pix[i:i + N])) for i in range(0, len(pix), N))
    c.append(f"static const uint8_t {slug}_px[] = {{\n{rows}\n}};")
    entries.append(f'    {{"{slug}", {len(frames)}, {len(p["palette"])}, {slug}_pal, {slug}_hold, {slug}_px}},')
    c.append("")
c.append("const sprite_t SPRITES[SPRITE_COUNT] = {")
c += entries
c.append("};")
open(os.path.join(root, "firmware", "src", "sprites.c"), "w").write("\n".join(c) + "\n")
open(os.path.join(root, "firmware", "src", "sprites.h"), "w").write(f"""#pragma once
#include <stdint.h>
#ifdef __cplusplus
extern "C" {{
#endif

#define SPRITE_COUNT {len(data['presets'])}
#define SPRITE_SIZE {N}

typedef struct {{
    const char *slug;
    uint8_t frames, colors;
    const uint8_t *palette;     // colors x (r, g, b, a)
    const uint16_t *hold_ms;    // per frame
    const uint8_t *pixels;      // frames x SIZE x SIZE palette indices
}} sprite_t;

extern const sprite_t SPRITES[SPRITE_COUNT];

#ifdef __cplusplus
}}
#endif
""")
print("wrote sprites.c/h", len(data["presets"]), "presets")
