"""Generate firmware/src/icons.c + icons.h: A8 (alpha-only) icons, recolored at runtime.

Claude and Codex marks are rasterized from assets/logos/*.svg (lobe-icons, MIT;
the marks themselves are trademarks of Anthropic and OpenAI, used here only to
label the service whose usage is shown). Replace the SVGs to change them.
Needs cairosvg + Pillow.   Usage: python3 tools/gen_icons.py
"""
import math, os
from PIL import Image, ImageDraw

SS = 8   # supersampling

def svg_icon(name):
    def render(n):
        import io, cairosvg
        png = cairosvg.svg2png(url=os.path.join(ROOT, "assets", "logos", name + ".svg"),
                               output_width=n * SS, output_height=n * SS)
        im = Image.open(io.BytesIO(png)).convert("RGBA")
        return im.split()[3]   # alpha as the mask
    return render

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
burst, terminal = svg_icon("claude"), svg_icon("codex")

ICONS = {"icon_burst12": (burst, 12), "icon_burst16": (burst, 16), "icon_burst40": (burst, 40),
         "icon_term16": (terminal, 16), "icon_term40": (terminal, 40)}

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "firmware", "src")
c = ['#include "lvgl.h"', "", "// Generated by tools/gen_icons.py, do not edit.", ""]
h = ["#pragma once", "#include <lvgl.h>", ""]
for name, (fn, n) in ICONS.items():
    data = list(fn(n).resize((n, n), Image.LANCZOS).tobytes())
    rows = ",\n".join("    " + ", ".join(str(v) for v in data[i:i + n]) for i in range(0, len(data), n))
    c += [f"static const uint8_t {name}_map[] = {{\n{rows}\n}};",
          f"const lv_image_dsc_t {name} = {{",
          f"    .header.magic = LV_IMAGE_HEADER_MAGIC, .header.cf = LV_COLOR_FORMAT_A8,",
          f"    .header.w = {n}, .header.h = {n}, .header.stride = {n},",
          f"    .data_size = {n * n}, .data = {name}_map,", "};", ""]
    h.append(f"LV_IMAGE_DECLARE({name});")
open(os.path.join(root, "icons.c"), "w").write("\n".join(c))
open(os.path.join(root, "icons.h"), "w").write("\n".join(h) + "\n")
print("wrote icons.c/icons.h")
